    "            step_result[\"errors\"].append(f\"Gesture: {e}\")\n"
    "    step_result[\"gesture_latency_ms\"] = (perf_time.time() - gest_start) * 1000.0\n"
    "    step_result[\"gesture\"] = current_gesture\n"
    "    step_result[\"gesture_confidence\"] = gesture_confidence\n"
    "\n"
    "    # 4. Agent decision pipeline\n"
    "    agent_start = perf_time.time()\n"
    "    if agent_service:\n"
    "        try:\n"
    "            agent_result = agent_service.decide({\n"
    "                \"observation_source\": \"integrated_pipeline\",\n"
    "                \"observation_type\": \"gesture\",\n"
    "                \"data\": {\"gesture\": current_gesture, \"hand\": handedness},\n"
    "                \"confidence\": gesture_confidence,\n"
    "            })\n"
    "            step_result[\"agent_action\"] = agent_result[\"selected_action\"]\n"
    "            step_result[\"permission_status\"] = agent_result[\"permission_status\"]\n"
    "            step_result[\"execution_status\"] = agent_result[\"execution_status\"]\n"
    "            step_result[\"verification_status\"] = agent_result[\"verification_status\"]\n"
    "            last_agent_decision = agent_result\n"
