    "\n"
    "    if hand_result:\n"
    "        if HAND_TRACKER_MODE == \"tasks\":\n"
    "            step_result[\"hands_detected\"] = len(hand_result.hand_landmarks) if hand_result.hand_landmarks else 0\n"
    "        elif HAND_TRACKER_MODE == \"legacy\":\n"
    "            step_result[\"hands_detected\"] = hand_result.num_hands\n"
    "\n"
    "    # 3. Gesture recognition + smoothing\n"
    "    gest_start = perf_time.time()\n"
    "    current_gesture = \"UNKNOWN\"\n"
    "    gesture_confidence = 0.0\n"
    "\n"
    "    if gesture_recognizer and gesture_smoother and hand_result:\n"
    "        try:\n"
    "            # Extract landmarks from hand result\n"
    "            landmarks = None\n"
    "            handedness = \"Right\"\n"
    "\n"
    "            if HAND_TRACKER_MODE == \"tasks\" and hand_result.hand_landmarks:\n"
    "                hl = hand_result.hand_landmarks[0]\n"
    "                landmarks = [(float(p.x), float(p.y), float(p.z)) for p in hl]\n"
    "                if hand_result.handedness and len(hand_result.handedness) > 0:\n"
    "                    handedness = hand_result.handedness[0][0].category_name\n"
    "            elif HAND_TRACKER_MODE == \"legacy\":\n"
    "                for hand in hand_result.hands:\n"
    "                    if hand.is_valid() and len(hand.landmarks) == 21:\n"
    "                        landmarks = hand.landmarks\n"
    "                        handedness = hand.handedness\n"
    "                        break\n"
    "                if landmarks and validate_landmarks(landmarks):\n"
    "                    pred = gesture_recognizer.recognize(landmarks, handedness=handedness)\n"
    "                current_gesture = pred.gesture\n"
    "                gesture_confidence = pred.confidence\n"
    "\n"
    "                # Smooth\n"
    "                smoothed = gesture_smoother.update(pred)\n"
    "                current_gesture = smoothed.gesture\n"
    "                gesture_confidence = smoothed.confidence\n"
    "                last_smoothed_gesture = current_gesture\n"
