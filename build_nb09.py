    "        except Exception as e:\n"
    "            step_result[\"errors\"].append(f\"Agent: {e}\")\n"
    "    step_result[\"agent_latency_ms\"] = (perf_time.time() - agent_start) * 1000.0\n"
    "\n"
    "    # 5. Total latency\n"
    "    step_result[\"total_latency_ms\"] = (perf_time.time() - step_start) * 1000.0\n"
    "\n"
    "    integrated_pipeline_results.append(step_result)\n"
    "    integrated_pipeline_frame += 1\n"
    "\n"
    "    return step_result\n"
    "\n"
