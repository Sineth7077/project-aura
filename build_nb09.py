    "        \"permission_status\": \"pending\",\n"
    "        \"execution_status\": \"skipped\",\n"
    "        \"verification_status\": \"pending\",\n"
    "        \"errors\": [],\n"
    "    }\n"
    "\n"
    "    step_start = perf_time.time()\n"
    "\n"
    "    # 1. YOLO object detection\n"
    "    yolo_start = perf_time.time()\n"
