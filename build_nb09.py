    "\n"
    "# Attach camera functions to the window object so they persist across eval_js\n"
    "# calls. In Colab, each eval_js() invocation runs in an isolated JavaScript\n"
    "# scope; functions defined without window. are not visible to later calls,\n"
    "# which caused \"captureFrame is not defined\".\n"
    "CAMERA_SETUP_JS = \"\"\"\n"
    "(function() {\n"
    "  // Idempotent: only register once even if the cell is re-run.\n"
    "  if (window.__aura_camera_registered__) return;\n"
    "  window.__aura_camera_registered__ = true;\n"
    "\n"
    "  async function setupCamera() {\n"
    "    const video = document.createElement('video');\n"
    "    video.setAttribute('playsinline', '');\n"
    "    video.setAttribute('autoplay', '');\n"
    "    video.style.width = '640px';\n"
    "    video.style.height = '480px';\n"
    "    video.style.border = '2px solid #333';\n"
    "    document.body.appendChild(video);\n"
    "    try {\n"
    "      const stream = await navigator.mediaDevices.getUserMedia({video: {width: 640, height: 480}});\n"
    "      video.srcObject = stream;\n"
    "      await new Promise((resolve) => {\n"
    "        video.onloadedmetadata = () => { resolve(); };\n"
    "      });\n"
    "      window.__aura_video__ = video;\n"
    "      return {status: 'ok', width: video.videoWidth, height: video.videoHeight};\n"
    "    } catch (err) {\n"
    "      return {status: 'error', message: String(err)};\n"
    "    }\n"
    "  }\n"
    "\n"
    "  async function captureFrame() {\n"
    "    const video = window.__aura_video__;\n"
    "    if (!video) return {status: 'error', message: 'Camera not initialized'};\n"
    "    const canvas = document.createElement('canvas');\n"
    "    canvas.width = video.videoWidth;\n"
    "    canvas.height = video.videoHeight;\n"
    "    canvas.getContext('2d').drawImage(video, 0, 0);\n"
    "    return {status: 'ok', data: canvas.toDataURL('image/jpeg', 0.85),\n"
    "            width: video.videoWidth, height: video.videoHeight};\n"
    "  }\n"
    "\n"
    "  async function stopCamera() {\n"
    "    const video = window.__aura_video__;\n"
    "    if (video && video.srcObject) {\n"
    "      const stream = video.srcObject;\n"
    "      const tracks = stream.getTracks();\n"
    "      tracks.forEach(track => track.stop());\n"
    "    }\n"
    "    const videoEl = document.querySelector('video');\n"
    "    if (videoEl) videoEl.remove();\n"
    "    window.__aura_video__ = null;\n"
    "    return {status: 'ok'};\n"
    "  }\n"
    "\n"
    "  window.setupCamera = setupCamera;\n"
    "  window.captureFrame = captureFrame;\n"
    "  window.stopCamera = stopCamera;\n"
