def make_notebook(cells, name):
    nb = {
        "cells": cells,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {
                "name": "python",
                "version": "3.11.9",
            },
        },
        "nbformat": 4,
        "nbformat_minor": 0,
    }
    path = os.path.join(NOTEBOOKS_DIR, name)
    with open(path, "w") as f:
        json.dump(nb, f, indent=1)
    print(f"Created: {path}")


